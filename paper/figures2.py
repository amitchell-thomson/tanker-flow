# Fig — one carrier's year: the three pairings on a timeline
# ----------------------------------------------------------------------

VESSEL_SQL = """
SELECT event_time, event_type, zone, terminal_id, laden_flag
FROM port_events WHERE mmsi = $1 AND event_time >= $2 AND event_time < $3
ORDER BY event_time
"""


async def fig_vessel(pool: asyncpg.Pool, mmsi: int = 224451000, year: int = 2024) -> None:
    """A single carrier's calendar year as legs, visits and queues.

    Each row is a terminal. A thick bar is a berth visit (moored -> departed),
    a hatched bar the anchorage wait before it, and a diagonal line a voyage
    leg (departed -> next zone entry elsewhere). Laden legs run US -> Europe,
    ballast legs run back. This is what `legs.py`, `visits.py` and
    `queues.py` pair, drawn rather than described.
    """
    lo = datetime(year, 1, 1, tzinfo=timezone.utc)
    hi = datetime(year + 1, 1, 1, tzinfo=timezone.utc)
    async with pool.acquire() as conn:
        ev = await conn.fetch(VESSEL_SQL, mmsi, lo, hi)
        terms = {r["terminal_id"]: (r["terminal_name"], r["zone"]) for r in await conn.fetch(TERMINAL_SQL)}
    _num("vesselFigureMmsi", str(mmsi))
    _num("vesselFigureYear", str(year))
    _num("vesselFigureEvents", len(ev))

    tids = sorted({r["terminal_id"] for r in ev if r["terminal_id"] is not None},
                  key=lambda t: (0 if terms[t][1].startswith("us") else 1, terms[t][0]))
    row = {t: i for i, t in enumerate(tids)}

    visits, queues, legs = [], [], []
    open_moored, open_anch, last_dep = {}, {}, None
    n_legs_laden = n_legs_ballast = 0
    for r in ev:
        t, et, ts = r["terminal_id"], r["event_type"], r["event_time"]
        if et == "anchorage_entry" and t not in open_anch:
            open_anch[t] = ts
        elif et == "moored":
            open_moored[t] = ts
            if t in open_anch:
                queues.append((t, open_anch.pop(t), ts))
        elif et == "departed":
            if t in open_moored:
                visits.append((t, open_moored.pop(t), ts, bool(r["laden_flag"])))
            open_anch.pop(t, None)
            last_dep = (t, ts, bool(r["laden_flag"]))
        elif et == "zone_entry" and last_dep is not None and last_dep[0] != t:
            legs.append((last_dep[0], last_dep[1], t, ts, last_dep[2]))
            if last_dep[2]:
                n_legs_laden += 1
            else:
                n_legs_ballast += 1
            last_dep = None
    _num("vesselFigureLadenLegs", n_legs_laden)
    _num("vesselFigureBallastLegs", n_legs_ballast)
    _num("vesselFigureVisits", len(visits))

    fig, ax = plt.subplots(figsize=(7.2, 3.6))
    for t, a, b in queues:
        ax.barh(row[t], (b - a).total_seconds() / 86400, left=a, height=0.55,
                color="none", edgecolor=BLUE, hatch="////", lw=0.6, zorder=2)
    for t, a, b, laden in visits:
        ax.barh(row[t], max((b - a).total_seconds() / 86400, 0.6), left=a, height=0.55,
                color=ACCENT if laden else INK, zorder=3)
    for t0, a, t1, b, laden in legs:
        ax.plot([a, b], [row[t0], row[t1]], color=ACCENT if laden else GREY,
                lw=1.1 if laden else 0.9, ls="-" if laden else "--", zorder=1)
    ax.set_yticks(range(len(tids)), [f"{terms[t][0]}" for t in tids], fontsize=7.5)
    ax.invert_yaxis()
    ax.axhline(sum(1 for t in tids if terms[t][1].startswith("us")) - 0.5, color=GREY, lw=0.6)
    ax.set_xlim(lo, hi)
    handles = [
        Patch(color=ACCENT, label="berth visit (leaves laden)"),
        Patch(color=INK, label="berth visit (leaves ballast)"),
        Patch(facecolor="none", edgecolor=BLUE, hatch="////", label="anchorage queue"),
        Line2D([0], [0], color=ACCENT, lw=1.1, label="laden leg"),
        Line2D([0], [0], color=GREY, lw=0.9, ls="--", label="ballast leg"),
    ]
    ax.legend(handles=handles, fontsize=7, loc="upper center", ncol=5, bbox_to_anchor=(0.5, -0.12))
    ax.set_title(f"MMSI {mmsi}, {year}: {len(visits)} visits, {n_legs_laden} laden and {n_legs_ballast} ballast legs",
                 fontsize=8.5, loc="left")
    _save(fig, "fig8_vessel_year")


