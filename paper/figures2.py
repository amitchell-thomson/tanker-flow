def _num(name: str, value) -> None:
    """Register a prose macro. Integers get thousands separators."""
    if isinstance(value, int):
        NUMBERS[name] = f"{value:,}"
    else:
        NUMBERS[name] = str(value)


def _write_numbers() -> None:
    lines = ["% GENERATED by paper/figures2.py — do not edit by hand"]
    for k in sorted(NUMBERS):
        lines.append(f"\\newcommand{{\\{k}}}{{{NUMBERS[k]}}}")
    NUMBERS2.write_text("\n".join(lines) + "\n")
    print(f"  wrote numbers2.tex ({len(NUMBERS)} macros)")


