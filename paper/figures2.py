RESCUE_SQL = """
SELECT rescue_class, result, count(*) AS n, sum(credits) AS credits
FROM vf_rescue_log GROUP BY 1, 2
"""
BALANCE_SQL = """
SELECT checked_at, credits, expiration_date FROM vf_account_status ORDER BY checked_at
"""


async def fig_rescue(pool: asyncpg.Pool) -> None:
    """Left: what each rescue class returned. Right: the account balance against
    the glide line that the daily cap is derived from."""
    async with pool.acquire() as conn:
        rows = await conn.fetch(RESCUE_SQL)
        bal = await conn.fetch(BALANCE_SQL)
    classes = sorted({r["rescue_class"] for r in rows},
                     key=lambda c: -sum(r["n"] for r in rows if r["rescue_class"] == c))
    results = ["rescued", "no_position", "skipped_budget", "other"]
    colour = {"rescued": GREEN, "no_position": GREY, "skipped_budget": "#e3e8f0", "other": RED}

    def bucket(res: str) -> str:
        return res if res in results else "other"

    m: dict[tuple[str, str], int] = {}
    for r in rows:
        m[(r["rescue_class"], bucket(r["result"]))] = m.get((r["rescue_class"], bucket(r["result"])), 0) + r["n"]
    credits_total = int(sum(r["credits"] or 0 for r in rows))
    rescued_total = int(sum(r["n"] for r in rows if r["result"] == "rescued"))
    skipped_total = int(sum(r["n"] for r in rows if r["result"] == "skipped_budget"))
    _num("nRescueLookups", int(sum(r["n"] for r in rows if r["result"] not in ("skipped_budget", "dry_run"))))
    _num("nRescued", rescued_total)
    _num("nRescueSkipped", skipped_total)
    _num("nRescueCredits", credits_total)

    fig, (ax0, ax1) = plt.subplots(1, 2, figsize=(7.2, 3.2), width_ratios=[1.25, 1])
    left = np.zeros(len(classes))
    for res in results:
        vals = np.array([m.get((c, res), 0) for c in classes], float)
        ax0.barh(range(len(classes)), vals, left=left, color=colour[res],
                 label=res.replace("_", " "), height=0.65, edgecolor="white", lw=0.4)
        left += vals
    ax0.set_yticks(range(len(classes)), [c.replace("_", " ") for c in classes], fontsize=7)
    ax0.invert_yaxis()
    ax0.set_xscale("symlog", linthresh=50)
    ax0.set_xlabel("lookups (symlog)")
    ax0.legend(fontsize=6.5, loc="lower right")

    if bal:
        ts = [r["checked_at"] for r in bal]
        cr = np.array([r["credits"] for r in bal], float)
        exp = bal[-1]["expiration_date"]
        ax1.plot(ts, cr, color=INK, lw=1.2, label="account balance")
        if exp is not None:
            ax1.plot([ts[0], exp], [cr[0], 0], color=ACCENT, lw=1.0, ls="--",
                     label="glide line to expiry")
            ax1.set_xlim(ts[0] - timedelta(days=5), exp + timedelta(days=10))
            _num("vfExpiry", exp.date().isoformat())
        _num("vfCreditsStart", int(cr[0]))
        _num("vfCreditsNow", int(cr[-1]))
        _num("vfCreditsAsOf", ts[-1].date().isoformat())
        ax1.set_ylim(0, cr.max() * 1.08)
        ax1.set_ylabel("VesselFinder credits")
        ax1.legend(fontsize=7, loc="upper right")
        for lab in ax1.get_xticklabels():
            lab.set_rotation(30)
            lab.set_ha("right")
    _save(fig, "fig10_rescue")


