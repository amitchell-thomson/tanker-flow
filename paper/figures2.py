LOADINGS_SQL = """
SELECT date_trunc('week', event_time)::date AS w, count(*) AS n
FROM port_events
WHERE event_type = 'departed' AND laden_flag AND regime = 'noaa'
  AND zone IN ('usgulf', 'usatlantic')
GROUP BY 1 ORDER BY 1
"""


async def fig_loadings(pool: asyncpg.Pool) -> None:
    """Weekly US laden departures on the NOAA feed, with the trailing
    four-week mean (the climatology null) and the EWMA at A4's fitted alpha."""
    async with pool.acquire() as conn:
        rows = await conn.fetch(LOADINGS_SQL)
    a4 = json.loads((RESULTS / "a4.json").read_text())
    alpha = float(a4["alpha_mean"])
    weeks = [r["w"] for r in rows]
    lo, hi = weeks[0], weeks[-1]
    grid = [lo + timedelta(days=7 * i) for i in range((hi - lo).days // 7 + 1)]
    have = {r["w"]: r["n"] for r in rows}
    y = np.array([have.get(w, 0) for w in grid], float)
    trail4 = np.array([y[max(0, i - 4):i].mean() if i >= 1 else np.nan for i in range(len(y))])
    ewma = np.full_like(y, np.nan)
    s = y[0]
    for i in range(1, len(y)):
        ewma[i] = s
        s = alpha * y[i] + (1 - alpha) * s
    _num("loadingsWeeklyPeak", int(y.max()))
    _num("loadingsWeeklyMeanTwentyFive", f"{y[[g.year == 2025 for g in grid]].mean():.1f}")
    _num("aFourAlphaFig", f"{alpha:.3f}")

    fig, ax = plt.subplots(figsize=(7.2, 3.0))
    ax.bar(grid, y, width=6, color="#d5dbe6", label="weekly laden departures (NOAA)")
    ax.plot(grid, trail4, color=INK, lw=1.0, label="trailing 4-week mean (climatology null)")
    ax.plot(grid, ewma, color=ACCENT, lw=1.0, label=f"EWMA, $\\alpha$ = {alpha:.3f} (A4 steady state)")
    ax.annotate("Freeport outage\n(June 2022)", xy=(date(2022, 6, 8), 22), xytext=(date(2020, 9, 1), 33),
                fontsize=7, arrowprops=dict(arrowstyle="-", color=GREY, lw=0.7))
    ax.annotate("COVID cargo\ncancellations", xy=(date(2020, 7, 6), 3), xytext=(date(2018, 10, 1), 20),
                fontsize=7, arrowprops=dict(arrowstyle="-", color=GREY, lw=0.7))
    ax.set_ylabel("cargoes per week")
    ax.set_xlim(date(2016, 1, 1), date(2026, 1, 1))
    ax.legend(fontsize=7, loc="upper left")
    _save(fig, "fig11_loadings")


