COVERAGE_SQL = """
SELECT date_trunc('quarter', event_time)::date AS q, regime, count(*) AS n
FROM port_events
WHERE event_time >= DATE '2016-01-01'
GROUP BY 1, 2 ORDER BY 1, 2
"""


async def fig_coverage(pool: asyncpg.Pool) -> None:
    """Where the events come from, quarter by quarter, and where each feed ends.

    The coverage seam of the paper (Section 3.5) is visible here as the point
    at which the two tall backfill series stop and only the thin live series
    remains. Drawn so the reader can see it before being told about it.
    """
    async with pool.acquire() as conn:
        rows = await conn.fetch(COVERAGE_SQL)
    quarters = sorted({r["q"] for r in rows})
    regimes = ["noaa", "gfw", "bbox", "mmsi_filter"]
    counts = {rg: np.zeros(len(quarters)) for rg in regimes}
    idx = {q: i for i, q in enumerate(quarters)}
    for r in rows:
        if r["regime"] in counts:
            counts[r["regime"]][idx[r["q"]]] = r["n"]

    fig, (ax0, ax1) = plt.subplots(
        2, 1, figsize=(7.2, 4.2), sharex=True, height_ratios=[1, 3.2]
    )
    spans = [
        ("NOAA archive", date(2016, 1, 1), date(2025, 12, 31), INK),
        ("GFW events", date(2016, 1, 1), date(2026, 2, 21), BLUE),
        ("live bbox", date(2026, 4, 1), date(2026, 5, 30), GREY),
        ("live MMSI filter", date(2026, 5, 30), date(2026, 8, 10), ACCENT),
    ]
    for i, (lab, lo, hi, col) in enumerate(spans):
        ax0.barh(i, (hi - lo).days, left=lo, height=0.6, color=col)
    ax0.set_yticks(range(len(spans)), [s[0] for s in spans], fontsize=7)
    ax0.invert_yaxis()
    ax0.grid(False)
    ax0.set_ylabel("feed span", fontsize=8)

    bottom = np.zeros(len(quarters))
    for rg in regimes:
        ax1.bar(
            quarters, counts[rg], width=80, bottom=bottom,
            color=REGIME_COLOUR[rg], label=REGIME_LABEL[rg], align="edge",
        )
        bottom += counts[rg]
    ax1.axvline(date(2025, 12, 31), color=RED, lw=0.9, ls="--")
    ax1.text(
        date(2025, 10, 1), bottom.max() * 0.92, "coverage seam\n(primary sample ends)",
        fontsize=7, color=RED, ha="right",
    )
    ax1.set_ylabel("port events per quarter")
    ax1.legend(fontsize=7.5, loc="upper left")
    ax1.set_xlim(date(2016, 1, 1), date(2026, 10, 1))
    _save(fig, "fig6_coverage")
    _num("nEventsPerQuarterPeak", int(bottom.max()))


