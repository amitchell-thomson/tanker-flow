ZONES_SQL = """
SELECT z.zone_type, z.sub_zone, ST_AsGeoJSON(z.geom) AS gj
FROM terminal_zones z WHERE z.terminal_id = $1
"""
ZONE_EVENTS_SQL = """
SELECT event_type, lat, lon FROM port_events
WHERE terminal_id = $1 AND lat IS NOT NULL AND lon IS NOT NULL
  AND event_type IN ('zone_entry','anchored','moored','departed')
ORDER BY random() LIMIT $2
"""
ZONE_COUNT_SQL = """
SELECT count(*) FROM port_events WHERE terminal_id = $1 AND lat IS NOT NULL
"""
TERMINAL_SQL = "SELECT terminal_id, terminal_name, zone FROM terminals"


def _rings(gj: str):
    g = json.loads(gj)
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    for poly in polys:
        yield np.array(poly[0])  # exterior ring, [lon, lat]


async def fig_zones(pool: asyncpg.Pool, terminal_id: int = 1, sample: int = 3000) -> None:
    """The hand-drawn polygons at Sabine Pass with a sample of the events
    the state machine emitted inside them. The approach envelope is the
    outer polygon; anchorage and berth are nested inside it."""
    async with pool.acquire() as conn:
        zones = await conn.fetch(ZONES_SQL, terminal_id)
        events = await conn.fetch(ZONE_EVENTS_SQL, terminal_id, sample)
        n_all = await conn.fetchval(ZONE_COUNT_SQL, terminal_id)
        terms = {r["terminal_id"]: r["terminal_name"] for r in await conn.fetch(TERMINAL_SQL)}
        n_polys = await conn.fetchval("SELECT count(*) FROM terminal_zones")
        n_terms = await conn.fetchval("SELECT count(*) FROM terminals")
    _num("nZonePolygons", int(n_polys))
    _num("nTerminals", int(n_terms))
    _num("nZoneFigureEvents", int(n_all))
    _num("zoneFigureTerminal", terms.get(terminal_id, str(terminal_id)))

    style = {
        "approach": dict(facecolor="#eef1f6", edgecolor=GREY, lw=0.8, zorder=1),
        "anchorage": dict(facecolor="#dbe6f5", edgecolor=BLUE, lw=0.9, zorder=2, hatch="//"),
        "berth": dict(facecolor="#f3e4c4", edgecolor=ACCENT, lw=1.0, zorder=3),
    }
    fig, ax = plt.subplots(figsize=(4.6, 4.9))
    for z in sorted(zones, key=lambda r: {"approach": 0, "anchorage": 1, "berth": 2}[r["zone_type"]]):
        for ring in _rings(z["gj"]):
            ax.add_patch(MplPolygon(ring, closed=True, **style[z["zone_type"]]))
    ev_style = {
        "zone_entry": (GREY, "o", 6),
        "anchored": (BLUE, "s", 9),
        "moored": (INK, "D", 9),
        "departed": (RED, "^", 10),
    }
    for et, (col, mk, sz) in ev_style.items():
        pts = [(r["lon"], r["lat"]) for r in events if r["event_type"] == et]
        if pts:
            xy = np.array(pts)
            ax.scatter(xy[:, 0], xy[:, 1], s=sz, marker=mk, color=col, alpha=0.55,
                       linewidths=0, zorder=4, label=f"{et.replace('_', ' ')} (n={len(pts)})")
    xs = np.concatenate([np.array([r["lon"] for r in events]), *[rg[:, 0] for z in zones for rg in _rings(z["gj"])]])
    ys = np.concatenate([np.array([r["lat"] for r in events]), *[rg[:, 1] for z in zones for rg in _rings(z["gj"])]])
    pad = 0.02
    ax.set_xlim(xs.min() - pad, xs.max() + pad)
    ax.set_ylim(ys.min() - pad, ys.max() + pad)
    ax.set_aspect(1 / np.cos(np.deg2rad(float(ys.mean()))))
    ax.set_xlabel("longitude")
    ax.set_ylabel("latitude")
    handles = [Patch(**{k: v for k, v in style[t].items() if k in ("facecolor", "edgecolor", "hatch")}, label=t)
               for t in ("approach", "anchorage", "berth")]
    handles += ax.get_legend_handles_labels()[0]
    ax.legend(handles=handles, fontsize=7, loc="lower right")
    ax.set_title(f"{terms.get(terminal_id, terminal_id)}: zone polygons and a sample of {len(events):,} events",
                 fontsize=8.5, loc="left")
    _save(fig, "fig7_zones")


